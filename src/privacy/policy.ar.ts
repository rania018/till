import { menuPath, type PolicyFacts, type PrivacyPolicy } from './types'

export function arPolicy({ m, operator, passphraseMin, expenseDays, billDays, keepDays, sync, push }: PolicyFacts): PrivacyPolicy {
  const settings = m.settings.title
  const reminders = m.settings.reminders
  const { name, email } = operator
  const features = [sync && 'المزامنة', push && 'التذكيرات وقت إغلاق التطبيق'].filter(Boolean).join(' أو ')

  return {
    intro:
      features
        ? 'يحفظ Till أموالك على جهازك. تشرح هذه الصفحة ما يخرج منه، ومتى، ومن يمكنه رؤيته، وكيف تحذفه. باختصار: لا يخرج شيء إلا إذا فعّلت ' + features + (sync ? '، والبيانات المتزامنة مشفّرة من طرف إلى طرف، فلا يمكن لأحد غيرك قراءتها، ولا حتى القائمون على Till.' : '.')
        : 'يحفظ Till أموالك على جهازك. تشرح هذه الصفحة ما يبقى فيه وكيف تحذفه. باختصار: لا يخرج شيء من جهازك.',
    sections: [
      ...(email || name
        ? [
            {
              title: 'من يدير Till',
              blocks: [
                // Worded without a gendered verb or adjective: the name can be anyone's.
                [name && `إدارة Till والمسؤولية عن البيانات الموصوفة هنا: ${name}.`, email && `لأي سؤال أو طلب يخص بياناتك، راسل ${email}.`].filter(Boolean).join(' '),
              ],
            },
          ]
        : []),
      {
        title: 'على جهازك',
        blocks: [
          'كل ما تدخله (المحافظ والمعاملات والفواتير والميزانيات والأهداف والديون والملاحظات والإعدادات) يُحفظ في هذا المتصفح على هذا الجهاز. ' + (features ? `لا يُرسل إلى أي مكان إلا إذا فعّلت ${features}.` : 'لا يُرسل إلى أي مكان.'),
          'يبقى رمز قفل التطبيق على هذا الجهاز، محفوظًا كتجزئة مملّحة لا يمكن استرجاع الأرقام منها. فتح القفل ببصمة الإصبع أو الوجه يمرّ عبر نظام جهازك: لا يتلقاها Till أبدًا.',
          'النسخ الاحتياطية وملفات الجداول المصدَّرة والمستوردة تُنشأ على جهازك. تذهب الملفات حيث تحفظها أو ترسلها.',
          'مسح بيانات هذا الموقع من متصفحك يحذف كل ما هنا، لذا احفظ نسخة احتياطية من حين لآخر' + (sync ? '، أو فعّل المزامنة.' : '.'),
        ],
      },
      {
        title: 'لا تتبّع',
        blocks: ['لا يحتوي Till على إعلانات ولا أدوات إحصاء ولا متتبّعات ولا ملفات تعريف ارتباط من أطراف أخرى. لا تُباع بياناتك ولا تؤجَّر ولا تُشارك مع أحد، ولا تُستخدم إلا لعمل التطبيق.'],
      },
      ...(sync
        ? [
            {
              title: `${m.sync.title} (اختياري)`,
              blocks: [
                'تسجيل الدخول عبر Google ينشئ لك حسابًا في مشروع Firebase الخاص بـ Till (خدمة من Google). يحتوي على بريدك الإلكتروني، والاسم ورابط صورة الملف الشخصي اللذين تشاركهما Google، وتاريخ إنشاء الحساب وآخر تسجيل دخول. تتولى Google عملية تسجيل الدخول نفسها وفق سياسة الخصوصية الخاصة بها.',
                `قبل أن يُرسل أي شيء إلى الإنترنت، يشفّره جهازك بمفتاح مقفل بعبارة مرور المزامنة (${passphraseMin} حرفًا على الأقل) وبمفتاح استرداد تحتفظ به أنت. لا تغادر عبارة المرور ولا مفتاح الاسترداد جهازك أبدًا. لا يمكن لأحد غيرك قراءة بياناتك المتزامنة: لا Google ولا القائمون على Till.`,
                'ما يمكن رؤيته على الإنترنت يقتصر على:',
                ['بريدك الإلكتروني ومعلومات تسجيل الدخول المذكورة أعلاه', 'معرّفات تبدو عشوائية لسجلاتك', 'وقت آخر حفظ لكل سجل', 'عدد سجلاتك وحجمها تقريبًا'],
                'إذا نسيت عبارة المرور وفقدت مفتاح الاسترداد، فلا يمكن لأحد فتح نسختك على الإنترنت، ولا حتى القائمون على Till. تحتفظ أجهزتك بنسخها الخاصة.',
                'تُخزَّن البيانات المتزامنة في مراكز بيانات Google ‏(Cloud Firestore وFirebase Authentication)، وقد تكون خارج بلدك.',
              ],
            },
          ]
        : []),
      ...(push
        ? [
            {
              title: 'التذكيرات وقت إغلاق التطبيق (اختياري)',
              blocks: [
                `إذا فعّلت ${menuPath(settings, reminders.title, reminders.push)}، يسجّل هذا الجهاز نفسه لدى خادم التذكيرات الخاص بـ Till ‏(Cloudflare Worker) بمعرّف جهاز عشوائي، ويرسل إليه:`,
                [
                  'عنوان الإشعارات الذي يمنحه متصفحك',
                  'منطقتك الزمنية ولغتك',
                  'يوم ووقت تذكيرك الأسبوعي، والأسبوع الذي تجاهلت فيه تذكيرًا',
                  'هل اكتمل الإعداد، واليوم الذي بدأت فيه',
                  `تواريخ (لا مبالغ) المصاريف التي سجّلتها يدويًا خلال آخر ${expenseDays} يومًا`,
                  `مواعيد استحقاق الفواتير غير المدفوعة خلال الـ ${billDays} يومًا القادمة`,
                ],
                'يُختم اسم الفاتورة ومبلغها على جهازك بمفتاح لا يغادره أبدًا. يحتفظ الخادم بهما ويمرّرهما دون أن يستطيع قراءتهما، ويفتحهما جهازك عند وصول التذكير.',
                'تصل الإشعارات عبر خدمة الإشعارات في متصفحك (Google أو Mozilla أو Apple)، مشفّرة بحيث لا تستطيع قراءتها.',
                `إيقاف الخيار يحذف هذه المعلومات من الخادم. يُحذف تلقائيًا أي جهاز لم يتصل منذ ${keepDays} يومًا.`,
              ],
            },
          ]
        : []),
      {
        title: 'الخوادم والسجلات',
        blocks: [
          'كأي موقع إلكتروني، ترى الخدمات التي توصل Till ‏(Firebase Hosting وGoogle Cloud وCloudflare) عنوان IP ومعلومات متصفحك، لتقديم التطبيق وحمايته من إساءة الاستخدام.' + (push ? ' يحتفظ خادم التذكيرات بسجلات تقنية قصيرة، مثل فشل إرسال، مع معرّف الجهاز العشوائي.' : '') + ' لا يستخدم Till أيًّا من ذلك للتعرّف عليك أو تتبّعك.',
        ],
      },
      {
        title: 'خياراتك',
        blocks: [
          [
            `الحصول على نسخة: ${menuPath(settings, m.data.title, m.data.exportBackup)}، أو ${m.data.exportCsv}.`,
            `تصحيح أي شيء: عدّله في التطبيق${sync ? '، وتنقل المزامنة التغيير' : ''}.`,
            ...(sync ? [`إيقاف المزامنة: ${menuPath(settings, m.settings.syncTitle, m.sync.signOut)}. تبقى بياناتك على جهازك وعلى الإنترنت.`] : []),
            ...(sync ? [`حذف نسختك على الإنترنت: ${menuPath(settings, m.settings.syncTitle, m.sync.deleteOnline)}. تُزال بياناتك المشفّرة ومفتاحك المقفل وحساب تسجيل دخولك من مشروع Firebase الخاص بـ Till.`] : []),
            `حذف كل شيء، على هذا الجهاز${sync ? ' وعلى الإنترنت' : ''}: ${menuPath(settings, m.data.title, m.data.reset)}.`,
            ...(push ? [`إيقاف التذكيرات وقت إغلاق التطبيق: أوقف «${reminders.push}».`] : []),
            ...(email
              ? [`لمعرفة ما يُحتفظ به عنك أو طلب حذفه: راسل ${email}.${sync ? ' ولأن البيانات المتزامنة مشفّرة، لا يستطيع القائمون على Till قراءتها أو إعادتها إليك، لكن يمكنهم حذفها.' : ''}`]
              : []),
          ],
        ],
      },
      {
        title: 'التغييرات',
        blocks: ['إذا تغيّرت هذه السياسة، تُنشر النسخة الجديدة هنا بتاريخ جديد في أعلاها.'],
      },
    ],
  }
}
