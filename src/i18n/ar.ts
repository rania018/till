/** Arabic has six plural forms; zero uses `other` here. */
function plural(n: number, forms: { one: string; two: string; few: string; many: string; other: string }): string {
  return forms[new Intl.PluralRules('ar').select(n) as keyof typeof forms] ?? forms.other
}

/** Arabic writes the plain number: يوم 15 من الشهر */
function ordinal(n: number): string {
  return `${n}`
}

